/** Gross → commission → net for one host call record. */
export function callEarning(c, cfg = HOST_EARNINGS) {
  const gross = c.minutes * cfg.rates[c.type];
  const commission = Math.round((gross * cfg.commission[c.type]) / 100);
  return { gross, commission, net: gross - commission };
}

